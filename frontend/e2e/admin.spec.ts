import { expect, test, type Page } from '@playwright/test'

const PASSWORD = process.env.E2E_PASSWORD ?? 'demo-pass'

async function login(page: Page) {
  await page.goto('/')
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel('Логин').fill('admin')
  await page.getByLabel('Пароль', { exact: true }).fill(PASSWORD)
  await page.getByRole('button', { name: 'Войти' }).click()
  await expect(page).toHaveURL(/\/campaigns$/)
}

const nav = (page: Page, name: string) => page.getByRole('navigation').getByRole('link', { name, exact: true })

test('неверный пароль — понятная ошибка, верный — вход', async ({ page }) => {
  await page.goto('/login')
  await page.getByLabel('Логин').fill('admin')
  await page.getByLabel('Пароль', { exact: true }).fill('wrong')
  await page.getByRole('button', { name: 'Войти' }).click()
  await expect(page.getByRole('alert')).toContainText('Неверный логин или пароль')
  await page.getByLabel('Пароль', { exact: true }).fill(PASSWORD)
  await page.getByRole('button', { name: 'Войти' }).click()
  await expect(page.getByRole('heading', { name: 'Заявки' })).toBeVisible()
})

test('заявка в панели: Enter по полям, повтор, панель заявки', async ({ page }) => {
  await login(page)
  await page.getByRole('link', { name: 'Заявка', exact: true }).click()
  const sheet = page.getByRole('dialog')
  await expect(sheet).toContainText('Новая заявка')

  await sheet.getByPlaceholder('ХОРГОС → БАКУ').fill('ХОРГОС → БАКУ')
  await page.keyboard.press('Enter')
  await expect(sheet.getByPlaceholder('Срочно, груз готов')).toBeFocused()
  await page.keyboard.type('Срочно')
  await page.keyboard.press('Enter')
  await page.keyboard.type('Тент 20 т')
  await page.keyboard.press('Shift+Enter')
  await page.keyboard.type('Реф 22 т')
  await page.keyboard.press('Enter')
  await expect(sheet.getByPlaceholder('Цемент')).toBeFocused()
  await page.keyboard.type('Мука')
  await page.keyboard.press('Enter')
  await expect(sheet.getByPlaceholder('Необязательно', { exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(sheet.getByPlaceholder('450 000 ₸')).toBeFocused()
  await page.keyboard.type('450 000 ₸')
  await expect(sheet.getByPlaceholder('120 м³ / 5 осей — 20 т')).toHaveValue('Тент 20 т\nРеф 22 т')
  await expect(sheet.locator('text=Реф 22 т').last()).toBeVisible()

  await sheet.getByRole('radio', { name: 'Повтор' }).click()
  await expect(sheet).toContainText('каждые 2 ч, 08:00–23:00')
  await page.screenshot({ path: 'e2e-results/form.png' })
  await sheet.getByRole('button', { name: 'Запланировать' }).click()

  await expect(page).toHaveURL(/\/campaigns\/\d+$/)
  await expect(page.getByRole('dialog')).toContainText('каждые 2 часа с 08:00 до 23:00')
  await page.screenshot({ path: 'e2e-results/campaign.png' })
  await page.keyboard.press('Escape')
  await expect(page).toHaveURL(/\/campaigns$/)
  await expect(page.getByRole('row', { name: /ХОРГОС → БАКУ/ }).first()).toContainText('каждые 2 ч')
})

test('список групп: заявка в список показывает его название', async ({ page }) => {
  await login(page)
  await nav(page, 'Группы').click()
  const boxes = page.locator('tbody input[type=checkbox]:not([disabled])')
  await boxes.nth(0).check()
  await boxes.nth(1).check()
  await page.getByRole('button', { name: 'Сохранить как список' }).click()
  await page.getByPlaceholder('Например, Тест').fill('Тест')
  await page.getByRole('dialog').getByRole('button', { name: 'Сохранить' }).click()
  await page.screenshot({ path: 'e2e-results/groups.png' })
  await page.getByRole('button', { name: 'Действия со списком' }).click()
  await page.getByRole('menuitem', { name: 'Заявка в этот список' }).click()

  const sheet = page.getByRole('dialog')
  await sheet.getByPlaceholder('ХОРГОС → БАКУ').fill('АЛМАТЫ → АСТАНА')
  await sheet.getByPlaceholder('Срочно, груз готов').fill('Завтра')
  await sheet.getByPlaceholder('120 м³ / 5 осей — 20 т').fill('Тент')
  await sheet.getByPlaceholder('Цемент').fill('Мука')
  await sheet.getByPlaceholder('450 000 ₸').fill('🔥')
  await expect(sheet).toContainText('→ Тест · сейчас')
  await sheet.getByPlaceholder('450 000 ₸').press('Control+Enter')
  await page.getByRole('dialog').getByRole('button', { name: 'Отправить' }).click()
  await expect(page).toHaveURL(/\/campaigns\/\d+$/)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('row', { name: /АЛМАТЫ → АСТАНА/ }).first()).toContainText('→ Тест')
})

