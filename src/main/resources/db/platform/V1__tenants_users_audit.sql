create table tenant (
    id bigint generated by default as identity primary key,
    name varchar(100) not null,
    status varchar(16) not null,
    legacy boolean default false not null,
    invite_code varchar(32) not null,
    created_at timestamp with time zone not null,
    constraint uq_tenant_name unique (name),
    constraint uq_tenant_invite unique (invite_code)
);

create table app_user (
    id bigint generated by default as identity primary key,
    tenant_id bigint references tenant (id) on delete cascade,
    login varchar(64) not null,
    password_hash varchar(100) not null,
    role varchar(16) not null,
    enabled boolean default true not null,
    session_version int default 0 not null,
    created_at timestamp with time zone not null,
    last_login_at timestamp with time zone,
    constraint uq_app_user_login unique (login)
);

create table audit_log (
    id bigint generated by default as identity primary key,
    at timestamp with time zone not null,
    actor_user_id bigint,
    actor_login varchar(64),
    tenant_id bigint,
    action varchar(32) not null,
    detail varchar(1000),
    ip varchar(64)
);

create index idx_audit_log_at on audit_log (at);
