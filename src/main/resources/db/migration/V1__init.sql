create table request (
    id varchar(64) primary key,
    sheet_row int,
    message clob not null,
    status varchar(16) not null,
    error varchar(1000),
    queued_at timestamp with time zone not null,
    started_at timestamp with time zone,
    completed_at timestamp with time zone
);

create index idx_request_status on request (status, queued_at);

create table wa_group (
    jid varchar(128) primary key,
    name varchar(512),
    archived boolean not null,
    member boolean,
    can_send boolean,
    active boolean not null,
    last_sync timestamp with time zone not null
);

create table delivery (
    id bigint generated by default as identity primary key,
    request_id varchar(64) not null references request (id),
    group_jid varchar(128) not null,
    position int not null,
    status varchar(16) not null,
    error varchar(1000),
    updated_at timestamp with time zone not null,
    constraint uq_delivery_request_group unique (request_id, group_jid)
);

create index idx_delivery_request on delivery (request_id, status, position);

create table risk_event (
    id bigint generated by default as identity primary key,
    type varchar(32) not null,
    group_jid varchar(128),
    request_id varchar(64),
    detail varchar(1000),
    created_at timestamp with time zone not null
);

create index idx_risk_event_created on risk_event (created_at);

create table daily_counter (
    counter_date date primary key,
    sent int not null,
    limit_value int
);
