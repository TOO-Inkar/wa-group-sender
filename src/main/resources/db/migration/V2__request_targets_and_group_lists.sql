-- Заявка может идти не во все активные группы, а в выбранные.
-- targeted хранится в самой заявке: заявка с выбранными группами никогда не превратится в рассылку по всем.
alter table request add column targeted boolean default false not null;

create table request_target (
    request_id varchar(64) not null references request (id),
    group_jid varchar(128) not null,
    constraint pk_request_target primary key (request_id, group_jid)
);

create table group_list (
    id bigint generated by default as identity primary key,
    name varchar(128) not null,
    created_at timestamp with time zone not null,
    constraint uq_group_list_name unique (name)
);

create table group_list_member (
    list_id bigint not null references group_list (id) on delete cascade,
    group_jid varchar(128) not null,
    constraint pk_group_list_member primary key (list_id, group_jid)
);
